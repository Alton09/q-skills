#!/usr/bin/env bash
# Hermetic tests for dossier.py. All homes, vaults, remotes, and clones are temporary.
set -u

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
script="$here/dossier.py"
command -v jq >/dev/null 2>&1 || { echo "jq is required" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home"
mkdir -p "$HOME" "$tmp/project/.claude"

n=0
out=
fail() {
  echo "FAIL case $n: $1" >&2
  [ -n "$out" ] && echo "  output: $out" >&2
  exit 1
}
pass() { echo "ok $n"; }
expect() {
  actual=$(jq -c "$1" <<<"$out" 2>/dev/null) || fail "output is not JSON ($1)"
  [ "$actual" = "$2" ] || fail "$1 = $actual, expected $2"
}
run() {
  out=$(python3 "$script" "$@")
  rc=$?
  [ "$rc" -eq 0 ] || fail "exit $rc"
  [ "$(printf '%s\n' "$out" | wc -l)" -eq 1 ] || fail "expected one JSON line"
}
configure_repo() {
  git -C "$1" config user.name "Dossier Test"
  git -C "$1" config user.email "dossier@example.invalid"
}

# 1. User pm keys merge with project keys; project wins key conflicts.
n=1
mkdir -p "$HOME/.claude" "$tmp/config-vault"
printf '%s\n' '{"pm":{"maxWorkers":5,"vault":"/wrong"}}' >"$HOME/.claude/workflow-kit.json"
printf '%s\n' "{\"pm\":{\"vault\":\"$tmp/config-vault\"}}" >"$tmp/project/.claude/workflow-kit.json"
run config --project-dir "$tmp/project"
expect .maxWorkers 5
expect .vault "\"$tmp/config-vault\""
expect .herdr true
expect 'has("warnings")' false
run resolve-vault --project-dir "$tmp/project"
expect .source '"config"'
expect .featuresDir "\"$tmp/config-vault/Features\""
printf '%s\n' '{"pm":{"vault":"'"$tmp/config-vault"'","herdr":false}}' >"$tmp/project/.claude/workflow-kit.json"
run config --project-dir "$tmp/project"
expect .herdr false
# User value is inherited unless the project overrides it.
printf '%s\n' '{"pm":{"herdr":false}}' >"$HOME/.claude/workflow-kit.json"
printf '%s\n' '{}' >"$tmp/project/.claude/workflow-kit.json"
run config --project-dir "$tmp/project"
expect .herdr false
printf '%s\n' '{"pm":{"herdr":true}}' >"$tmp/project/.claude/workflow-kit.json"
run config --project-dir "$tmp/project"
expect .herdr true
printf '%s\n' '{"pm":{"herdr":"false"}}' >"$tmp/project/.claude/workflow-kit.json"
run config --project-dir "$tmp/project"
expect .herdr true
expect .warnings '["pm.herdr must be a boolean; using true"]'
pass

# 2. init is byte-idempotent and adds each union attribute exactly once.
n=2
vault="$tmp/vault"
run init --vault "$vault" --feature alpha
before=$(find "$vault" -type f -print0 | sort -z | xargs -0 sha256sum)
run init --vault "$vault" --feature alpha
after=$(find "$vault" -type f -print0 | sort -z | xargs -0 sha256sum)
[ "$before" = "$after" ] || fail "second init changed bytes"
[ "$(grep -Fxc 'decisions.md merge=union' "$vault/.gitattributes")" -eq 1 ] || fail "decisions union line count"
[ "$(grep -Fxc 'log.md merge=union' "$vault/.gitattributes")" -eq 1 ] || fail "log union line count"
[ "$(grep -Fxc 'ignored.md merge=union' "$vault/.gitattributes")" -eq 1 ] || fail "ignored union line count"
[ -d "$vault/Features/_project/items" ] || fail "project items directory missing"
printf '# Log\n\n' >"$tmp/expected-log"
cmp -s "$tmp/expected-log" "$vault/Features/_project/log.md" || fail "project log content"
grep -Fq '## Architecture' "$vault/Features/alpha/brief.md" || fail "brief headings missing"
pass

# 3. Item lists, empty values, and body survive set/get; add deduplicates.
n=3
feature="$vault/Features/alpha"
run item new --feature-dir "$feature" --slug api --title 'API, bridge' --set stage=design --set 'files=["a.py", "b.py"]' --set question=
item="$feature/items/api.md"
printf '\nExisting body.\n' >>"$item"
run item set "$item" status=queued 'modules=["core", "web"]' question= --add files=b.py --add files=c.py --add notified=plan-done --add notified=plan-done --note 'queued for design'
run item get "$item"
expect '.item.files' '["a.py","b.py","c.py"]'
expect '.item.modules' '["core","web"]'
expect '.item.question' '""'
expect '.item.notified' '["plan-done"]'
expected_body=$(printf '\nExisting body.\n- %s queued for design\n' "$(date +%F)" | jq -Rs .)
expect .body "$expected_body"
pass

# 4. Board follows stage order and list excludes _project while returning matches.
n=4
run board --feature-dir "$feature"
expect .items 1
grep -Fq '> Generated by dossier.py board; do not edit.' "$feature/board.md" || fail "generated note missing"
grep -Fq '| [[items/api]] | queued |' "$feature/board.md" || fail "item row missing"
run list --vault "$vault" --match alpa
expect '.features | map(.name)' '["alpha"]'
expect .closest '["alpha"]'
pass

# Prepare a tracked vault and two clones before either concurrent append.
remote="$tmp/remote.git"
git init --bare --initial-branch=main "$remote" >/dev/null
seed="$tmp/seed"
git clone "$remote" "$seed" >/dev/null 2>&1
configure_repo "$seed"
cp -R "$vault/." "$seed/"
git -C "$seed" add -A
git -C "$seed" commit -m seed >/dev/null
git -C "$seed" push -u origin main >/dev/null 2>&1
clone_a="$tmp/clone-a"
clone_b="$tmp/clone-b"
git clone "$remote" "$clone_a" >/dev/null 2>&1
git clone "$remote" "$clone_b" >/dev/null 2>&1
configure_repo "$clone_a"
configure_repo "$clone_b"

# 5. Concurrent append-only decision commits both survive union merge and push.
n=5
printf '%s\n' '- 2026-10-14 [project] choice A — reason (design review)' >>"$clone_a/Features/_project/decisions.md"
run sync --vault "$clone_a" -m 'choice A' -- Features/_project/decisions.md
expect .ok true
printf '%s\n' '- 2026-10-14 [project] choice B — reason (user reversal)' >>"$clone_b/Features/_project/decisions.md"
run sync --vault "$clone_b" -m 'choice B' -- Features/_project/decisions.md
expect .ok true
git -C "$clone_a" pull --ff-only >/dev/null 2>&1 || fail "refresh clone A"
grep -Fq 'choice A' "$clone_a/Features/_project/decisions.md" || fail "choice A lost"
grep -Fq 'choice B' "$clone_a/Features/_project/decisions.md" || fail "choice B lost"
pass

# 6. A receive hook rejects exactly once; sync recognizes rejection and retries.
n=6
marker="$tmp/rejected-once"
hook="$remote/hooks/pre-receive"
printf '%s\n' '#!/usr/bin/env bash' "if [ ! -e '$marker' ]; then" "  : >'$marker'" "  echo 'rejected once' >&2" '  exit 1' 'fi' 'exit 0' >"$hook"
chmod +x "$hook"
printf '%s\n' '- 2026-10-14 retried push' >>"$clone_a/Features/alpha/log.md"
run sync --vault "$clone_a" -m 'retry push' -- Features/alpha/log.md
expect .ok true
expect .attempts 2
[ -e "$marker" ] || fail "reject hook did not run"
pass

# 7. A real non-board rebase conflict returns paths and aborts the rebase.
n=7
conflict_a="$tmp/conflict-a"
conflict_b="$tmp/conflict-b"
git clone "$remote" "$conflict_a" >/dev/null 2>&1
git clone "$remote" "$conflict_b" >/dev/null 2>&1
configure_repo "$conflict_a"
configure_repo "$conflict_b"
sed -i 's/^## Goal$/## Goal from A/' "$conflict_a/Features/alpha/brief.md"
run sync --vault "$conflict_a" -m 'brief A' -- Features/alpha/brief.md
expect .ok true
sed -i 's/^## Goal$/## Goal from B/' "$conflict_b/Features/alpha/brief.md"
run sync --vault "$conflict_b" -m 'brief B' -- Features/alpha/brief.md
expect .ok false
expect '.conflict | map(endswith("brief.md"))' '[true]'
[ ! -d "$conflict_b/.git/rebase-merge" ] || fail "rebase-merge still present"
[ ! -d "$conflict_b/.git/rebase-apply" ] || fail "rebase-apply still present"
pass

# 8. Fixture settings report missing allow rule and missing trust with fixes.
n=8
rm -f "$HOME/.claude/settings.json" "$HOME/.claude/settings.local.json" "$HOME/.claude.json"
printf '%s\n' '{"permissions":{"defaultMode":"plan","allow":["Bash(git status)"]}}' >"$tmp/project/.claude/settings.json"
printf '%s\n' '{"permissions":{"allow":["Read(*)"]}}' >"$tmp/project/.claude/settings.local.json"
printf '%s\n' '{"projects":{}}' >"$HOME/.claude.json"
run checks --project-dir "$tmp/project"
expect .allowRule false
expect .trusted false
expect .permissionMode '"plan"'
expect '.fixes | length' 2
expect '.fixes[0]' '"run /permissions and allow Bash(claude --bg *)"'
expect '.fixes[1]' "\"open Claude Code in $tmp and accept the trust dialog\""
pass

# 9. Either accepted allow syntax and an ancestor trust entry satisfy checks.
n=9
printf '%s\n' '{"permissions":{"allow":["Bash(claude --bg:*)"]}}' >"$HOME/.claude/settings.local.json"
printf '%s\n' "{\"projects\":{\"$tmp\":{\"hasTrustDialogAccepted\":true}}}" >"$HOME/.claude.json"
run checks --project-dir "$tmp/project"
expect .allowRule true
expect .trusted true
expect .fixes '[]'
pass

# 10. Unknown keys and invalid enum values are usage errors (exit 2).
n=10
python3 "$script" item set "$item" unknown=value >"$tmp/bad.out" 2>"$tmp/bad.err"
rc=$?
[ "$rc" -eq 2 ] || fail "unknown key exit $rc"
python3 "$script" item set "$item" stage=nonsense >"$tmp/bad.out" 2>"$tmp/bad.err"
