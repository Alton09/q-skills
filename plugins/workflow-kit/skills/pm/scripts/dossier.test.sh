printf '# Inbox\n\n> Generated by scan.py scan; do not edit.\n\n- `pr:123` Fix login crash — branch `fix-login`, worktree `/abs/path`, author `alice`\n- `branch:spike` Spike  \n' >"$board_vault/Features/_project/inbox.md"
run board --feature-dir "$board_vault/Features/alpha"
cp "$board_vault/Features/alpha/board.md" "$tmp/feature-before"
# Build the exact legacy feature-board format independently.
{
  printf '# Board\n\n> Generated by dossier.py board; do not edit.\n'
  for stage in idea design plan implement pr review merged done dropped; do
    printf '\n## %s\n\n| Item | Status | PR | Worker | Updated |\n|---|---|---|---|---|\n' "$stage"
    case "$stage" in
      implement) slugs='able zulu' ;;
      done) slugs=finished ;;
      dropped) slugs=abandoned ;;
      *) slugs= ;;
    esac
    for slug in $slugs; do
      run item get "$board_vault/Features/alpha/items/$slug.md"
      updated=$(jq -r .item.updated <<<"$out")
      printf '| [[items/%s]] | queued |  |  | %s |\n' "$slug" "$updated"
    done
  done
} >"$tmp/legacy-board"
cmp -s "$tmp/legacy-board" "$tmp/feature-before" || fail "legacy feature board changed"
mkdir -p "$board_vault/Features/malformed/items"
printf 'not frontmatter\n' >"$board_vault/Features/malformed/items/broken.md"
run board --project --vault "$board_vault"
expect '.warnings | length' 1
[[ $(jq -r '.warnings[0]' <<<"$out") == *malformed/items/broken.md* ]] || fail "missing malformed item warning"
