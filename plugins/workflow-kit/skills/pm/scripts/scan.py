#!/usr/bin/env python3
"""Discover, adopt, and ignore repo activity outside this vault's dossiers."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
from typing import Any, Sequence

import dossier


INBOX_HEADER = "# Inbox\n\n> Generated by scan.py scan; do not edit.\n\n"
FIELDS = ("pr", "branch", "worktree", "session")


def run(argv: Sequence[str], cwd: Path) -> tuple[bool, str, str]:
    """The only external-tool boundary; unavailable and hung tools are failures."""
    try:
        result = subprocess.run(argv, cwd=cwd, text=True, capture_output=True, timeout=30, check=False)
        return result.returncode == 0, result.stdout, result.stderr
    except (OSError, subprocess.TimeoutExpired, UnicodeError) as exc:
        return False, "", str(exc)


def resolved(value: str, base: Path) -> str:
    path = Path(value).expanduser()
    return str((path if path.is_absolute() else base / path).resolve())


def inbox_path(vault: Path) -> Path:
    return vault / "Features" / dossier.PROJECT_DIR / "inbox.md"


def write_inbox(vault: Path, lines: Sequence[str]) -> tuple[str, bool]:
    path = inbox_path(vault)
    content = INBOX_HEADER + "\n".join(lines or ["- (empty)"]) + "\n"
    changed = not path.exists() or path.read_text(encoding="utf-8") != content
    if changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return str(path), changed


def entry_line(entry: dict[str, Any]) -> str:
    # Keep each discovery on one line, including titles supplied by external tools.
    clean = lambda value: " ".join(str(value).splitlines()).replace("`", "'")
    line = f"- `{entry['key']}`"
    if entry["title"]:
        line += " " + clean(entry["title"])
    parts = [f"{field} `{clean(entry[field])}`" for field in ("branch", "worktree", "session", "author") if entry[field]]
    if parts:
        line += " — " + ", ".join(parts)
    return line


def scan(vault: Path, project_dir: Path, exclude_sessions: Sequence[str] = ()) -> dict[str, Any]:
    vault, project_dir = vault.resolve(), project_dir.resolve()
    warnings: list[str] = []

    def source(argv: list[str], json_output: bool = False) -> Any:
        ok, stdout, stderr = run(argv, project_dir)
        if not ok:
            warnings.append(f"{' '.join(argv)}: {(stderr or stdout).strip() or 'command failed'}")
            return [] if json_output else ""
        if not json_output:
            return stdout
        try:
            value = json.loads(stdout)
            if not isinstance(value, list) or any(not isinstance(row, dict) for row in value):
                raise ValueError("expected an array of objects")
            return value
        except (ValueError, TypeError) as exc:
            warnings.append(f"{' '.join(argv)}: invalid JSON: {exc}")
            return []

    prs = source(["gh", "pr", "list", "--state", "open", "--limit", "200", "--json", "number,title,headRefName,author,isDraft"], True)
    closed_branches = set()
    for state in ("merged", "closed"):
        closed_branches.update(row.get("headRefName") for row in source(
            ["gh", "pr", "list", "--state", state, "--limit", "200", "--json", "headRefName"], True
        ) if isinstance(row.get("headRefName"), str))
    worktrees = []
    for record in source(["git", "worktree", "list", "--porcelain"]).strip().split("\n\n"):
        fields = dict(line.split(" ", 1) for line in record.splitlines() if " " in line)
        if fields.get("worktree"):
            worktrees.append({"worktree": resolved(fields["worktree"], project_dir),
                              "branch": fields.get("branch", "").removeprefix("refs/heads/")})
    default = source(["git", "symbolic-ref", "--short", "refs/remotes/origin/HEAD"]).strip().removeprefix("origin/") or "main"
    branches = source(["git", "branch", "--format=%(refname:short)", "--no-merged", default]).splitlines()
    rows: list[dict[str, Any]] = []
    for pr in prs:
        if not isinstance(pr.get("number"), int) or not pr.get("headRefName"):
            warnings.append("gh open PR: missing number or headRefName")
            continue
        author = pr.get("author") or {}
        rows.append({"pr": str(pr["number"]), "title": pr.get("title", ""), "branch": pr["headRefName"],
                     "author": author.get("login", "") if isinstance(author, dict) else str(author), "draft": bool(pr.get("isDraft"))})
    rows.extend(worktrees[1:])
    rows.extend({"branch": branch} for branch in branches if branch and branch != default and branch not in closed_branches)
    sessions = source(["claude", "agents", "--json", "--all"], True)
    if sessions and not any(isinstance(row.get("cwd"), str) and row["cwd"] for row in sessions):
        warnings.append("claude agents: no cwd field; skipping sessions")
        sessions = []
    roots = {project_dir, *(Path(row["worktree"]) for row in worktrees)}
    labels = {dossier.feature_label(path.name) for path in (vault / "Features").glob("*") if path.is_dir()}
    retro = re.compile(r"(.+)-retro-\d+\Z")
    for session in sessions:
        name, cwd = session.get("name"), session.get("cwd")
        if not isinstance(name, str) or not name or not isinstance(cwd, str) or not cwd:
            continue
        match = retro.fullmatch(name)
        if name in exclude_sessions or (match and match[1] in labels):
            continue
        if str(session.get("state", session.get("status", ""))).lower() in ("done", "finished", "completed", "failed", "cancelled", "canceled", "stopped", "exited"):
            continue
        directory = Path(resolved(cwd, project_dir))
        if not any(directory.is_relative_to(root) for root in roots):
            continue
        row = {"session": name}
        # A session in a worktree subdirectory inherits that worktree's branch.
        containing = sorted((wt for wt in worktrees[1:] if directory.is_relative_to(Path(wt["worktree"]))),
                            key=lambda wt: len(wt["worktree"]), reverse=True)
        if containing:
            row["branch"] = containing[0]["branch"]
            row["worktree"] = containing[0]["worktree"]
        if isinstance(session.get("branch"), str) and session["branch"]:
            row["branch"] = session["branch"]
        rows.append(row)

    tracked: dict[str, set[str]] = {field: set() for field in FIELDS}
    for path in sorted((vault / "Features").glob("*/items/*.md")):
        try:
            item, _ = dossier.parse_item(path)
            for field in FIELDS:
                value = item.get("worker" if field == "session" else field)
                if isinstance(value, str) and value:
                    if field == "pr":
                        match = re.fullmatch(r"(?:https?://[^\s]+/pull/|#)?(\d+)/?", value)
                        if match:
                            value = match[1]
                    tracked[field].add(resolved(value, project_dir) if field == "worktree" else value)
        except dossier.UsageError as exc:
            warnings.append(str(exc))

    # Connected components preserve links even when a later row joins two groups.
    groups: list[list[dict[str, Any]]] = []
    for row in rows:
        joined = [row]
        remaining = []
        for group in groups:
            if any(row.get(field) and row.get(field) == other.get(field) for other in group for field in FIELDS):
                joined.extend(group)
            else:
                remaining.append(group)
        groups = remaining + [joined]
    ignored_path = vault / "Features" / dossier.PROJECT_DIR / "ignored.md"
    ignored = set(ignored_path.read_text(encoding="utf-8").splitlines()) if ignored_path.exists() else set()
    entries = []
    for group in groups:
        if any(str(row.get(field, "")) in tracked[field] for row in group for field in FIELDS):
            continue
        entry = {field: "" for field in ("title", *FIELDS, "author")}
        entry["draft"] = False
        # Prefer the PR's title and metadata; otherwise retain deterministic first values.
        for row in sorted(group, key=lambda row: (not bool(row.get("pr")), json.dumps(row, sort_keys=True))):
            for field in entry:
                if not entry[field] and row.get(field):
                    entry[field] = row[field]
        entry["key"] = next(f"{field}:{entry[field]}" for field in FIELDS if entry[field])
        if not any(f"{field}:{row[field]}" in ignored for row in group for field in FIELDS if row.get(field)):
            entries.append(entry)
    entries.sort(key=lambda entry: entry["key"])
    inbox, changed = write_inbox(vault, [entry_line(entry) for entry in entries])
    return {"ok": True, "entries": entries, "warnings": warnings, "inbox": inbox, "changed": changed}


def safe_name(value: str) -> str:
    if not value or value in (".", "..") or any(char in value for char in "/\\\n\r"):
        raise dossier.UsageError(f"invalid name: {value}")
    return value


def adopt(args: argparse.Namespace) -> dict[str, Any]:
    vault = Path(args.vault).expanduser().resolve()
    feature = dossier.PROJECT_DIR if args.standalone else safe_name(args.feature)
    directory = vault / "Features" / feature
    if not args.standalone and not directory.is_dir():
        raise dossier.UsageError(f"feature does not exist: {feature}")
    safe_name(args.slug)
    result = scan(vault, Path(args.project_dir).expanduser(), args.exclude_session)
    entry = next((entry for entry in result["entries"] if entry["key"] == args.key), None)
    if entry is None:
        raise dossier.UsageError(f"discovery key absent: {args.key}")
    assignments = ["origin=external", "status=idle", "stage=" + ("pr" if entry["pr"] else "implement")]
    for field in FIELDS:
        if entry[field]:
            assignments.append(f"{'worker' if field == 'session' else field}={json.dumps(str(entry[field]))}")
    created = dossier.item_new(directory, args.slug, args.title if args.title is not None else (entry["title"] or entry["key"]), assignments)
    inbox, _ = write_inbox(vault, [entry_line(other) for other in result["entries"] if other["key"] != args.key])
    return {"ok": True, "file": created["file"], "item": created["item"], "inbox": inbox}


def ignore(vault: Path, key: str) -> dict[str, Any]:
    if not key or any(char in key for char in "\n\r`"):
        raise dossier.UsageError("invalid discovery key")
    vault = vault.expanduser().resolve()
    path = vault / "Features" / dossier.PROJECT_DIR / "ignored.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text("# Ignored discovery keys\n\n", encoding="utf-8")
    dossier.append_missing_lines(path, [key])
    inbox = inbox_path(vault)
    lines = inbox.read_text(encoding="utf-8").splitlines() if inbox.exists() else []
    write_inbox(vault, [line for line in lines if line.startswith("- `") and not line.startswith(f"- `{key}` ") and line != f"- `{key}`"])
    return {"ok": True, "ignored": str(path), "inbox": str(inbox)}


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(description=__doc__)
    commands = root.add_subparsers(dest="action", required=True)
    discover = commands.add_parser("scan")
    discover.add_argument("--exclude-session", action="append", default=[])
    take = commands.add_parser("adopt")
    target = take.add_mutually_exclusive_group(required=True)
    target.add_argument("--feature")
    target.add_argument("--standalone", action="store_true")
    take.add_argument("--slug", required=True)
    take.add_argument("--title")
    take.add_argument("--exclude-session", action="append", default=[])
    skip = commands.add_parser("ignore")
    for command in (discover, take, skip):
        command.add_argument("--vault", required=True)
    for command in (discover, take):
        command.add_argument("--project-dir", required=True)
    for command in (take, skip):
        command.add_argument("--key", required=True)
    return root


def main(argv: Sequence[str] | None = None) -> int:
    try:
        args = parser().parse_args(argv)
        if args.action == "scan":
            result = scan(Path(args.vault).expanduser(), Path(args.project_dir).expanduser(), args.exclude_session)
        elif args.action == "adopt":
            result = adopt(args)
        else:
            result = ignore(Path(args.vault), args.key)
    except (dossier.UsageError, OSError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False))
        return 2
    print(json.dumps(result, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
